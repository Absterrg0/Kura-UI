import { cn } from "@/lib/cn";
import { highlight } from "@/lib/highlight";
import { CopyButton } from "./copy-button";

export async function CodeBlock({
  code,
  lang = "tsx",
  title,
  className,
  maxHeight = true,
}: {
  code: string;
  lang?: string;
  title?: string;
  className?: string;
  maxHeight?: boolean;
}) {
  const html = await highlight(code, lang);
  return (
    <div
      data-slot="code-block"
      className={cn(
        "group relative overflow-hidden rounded-[8px] bg-kura-surface shadow-[inset_0_0_0_1px_var(--kura-border)]",
        className,
      )}
    >
      {title && (
        <div className="flex h-9 items-center border-kura-border-subtle border-b px-4 font-kura-mono text-[11px] text-kura-fg-subtle uppercase tracking-[0.12em]">
          {title}
        </div>
      )}
      <CopyButton
        value={code}
        label="Copy code"
        className={cn("absolute right-2 z-10", title ? "top-1.5" : "top-2")}
      />
      <div
        className={cn(
          "overflow-auto p-4 pr-12 font-kura-mono text-[13px] leading-relaxed [&_pre]:outline-none",
          maxHeight && "max-h-[480px]",
        )}
        // biome-ignore lint/security/noDangerouslySetInnerHtml: trusted, generated by shiki at build time
        dangerouslySetInnerHTML={{ __html: html }}
      />
    </div>
  );
}

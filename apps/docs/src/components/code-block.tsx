import { cn } from "@/lib/cn";
import { highlight } from "@/lib/highlight";
import { CopyButton } from "./copy-button";

/** A code pane: a sunk well in the page's theme, with monochrome ink syntax. */
export async function CodeBlock({
  code,
  lang = "tsx",
  title,
  className,
  maxHeight = true,
}: {
  code: string;
  lang?: string;
  title?: string;
  className?: string;
  maxHeight?: boolean;
}) {
  const html = await highlight(code, lang);
  const copy = <CopyButton value={code} label="Copy code" className="shrink-0" />;
  const pane = (
    <div
      // biome-ignore lint/a11y/noNoninteractiveTabindex: scrollable region must be keyboard-reachable
      tabIndex={0}
      className={cn(
        "min-w-0 flex-1 overflow-auto p-4 font-kura-mono text-[13px] leading-relaxed outline-hidden focus-visible:shadow-[inset_0_0_0_2px_var(--kura-ring)] [&_pre]:outline-hidden",
        title && "pt-1",
        maxHeight && "max-h-[480px]",
      )}
      // biome-ignore lint/security/noDangerouslySetInnerHtml: trusted, generated by shiki at build time
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
  return (
    <div
      data-slot="code-block"
      className={cn("well group relative overflow-hidden rounded-kura-lg text-kura-fg", className)}
    >
      {title ? (
        <>
          <div className="flex h-10 items-center justify-between gap-3 pr-2 pl-4 font-kura-mono text-[12px] text-kura-fg-subtle">
            <span className="min-w-0 truncate">{title}</span>
            {copy}
          </div>
          {pane}
        </>
      ) : (
        // The copy key sits beside the code, never over it.
        <div className="flex items-start">
          {pane}
          <div className="shrink-0 py-3 pr-2">{copy}</div>
        </div>
      )}
    </div>
  );
}
